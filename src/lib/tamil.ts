// Picks the Tamil content for a page path (e.g. "/gst-litigation-salem").
// Returns null for pages without a Tamil summary.
export function tamilFor(path: string): TamilContent | null {
  const slug = path.replace(/^\//, "");
  if (slug === "") return home();
  if (slug === "private-limited-company-incorporation-chennai") return company(PLACE_TA.chennai);
  if (slug === "virtual-cfo-services") return vcfo();
  if (slug === "gst-notice-reply-chennai") return gst(PLACE_TA.chennai);
  if (slug === "income-tax-notice-reply-chennai") return incomeTax(PLACE_TA.chennai);
  if (slug === "nri-property-sale-tds-chennai" || slug.startsWith("nri-tax-services")) return nri();
  let m = slug.match(/^company-registration-(.+)$/);
  if (m && PLACE_TA[m[1]]) return company(PLACE_TA[m[1]]);
  m = slug.match(/^gst-litigation-(.+)$/);
  if (m && PLACE_TA[m[1]]) return gst(PLACE_TA[m[1]]);
  m = slug.match(/^income-tax-consultant-(.+?)(-chennai)?$/);
  if (m && PLACE_TA[m[1]]) return m[2] ? area(PLACE_TA[m[1]]) : incomeTax(PLACE_TA[m[1]]);
  m = slug.match(/^chartered-accountant-(.+)-chennai$/);
  if (m && PLACE_TA[m[1]]) return area(PLACE_TA[m[1]]);
  return null;
}
