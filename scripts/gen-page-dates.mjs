// Writes src/lib/page-dates.ts: the date each page's content last changed in
// git, used for sitemap <lastmod> and the "Reviewed … Updated" line.
// Run after committing content changes:  npm run page-dates
import { execFileSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const APP = "src/app";
const SKIP = new Set(["admin", "api", "blog"]); // blog posts carry their own dates

function pages(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (SKIP.has(name) || name.startsWith("[") || name.startsWith("(")) continue;
      out.push(...pages(full));
    } else if (name === "page.tsx") out.push(full);
  }
  return out;
}

const dates = {};
for (const file of pages(APP)) {
  const route = "/" + relative(APP, file).split(sep).slice(0, -1).join("/");
  const date = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], { encoding: "utf8" }).trim();
  if (date) dates[route === "/" ? "/" : route] = date;
}

const body = Object.keys(dates).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(dates[k])},`).join("\n");
writeFileSync(
  "src/lib/page-dates.ts",
  `// Generated by scripts/gen-page-dates.mjs — do not edit by hand.\n// Last git change of each page's content (YYYY-MM-DD).\nexport const PAGE_DATES: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`page-dates: ${Object.keys(dates).length} routes`);
